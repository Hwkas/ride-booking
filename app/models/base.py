from datetime import datetime
from enum import Enum

import sqlalchemy as sa

from sqlalchemy import DateTime, MetaData, func
from sqlalchemy.orm import DeclarativeBase, Mapped, MappedAsDataclass, mapped_column


# Deterministic constraint names so Alembic migrations stay stable.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(MappedAsDataclass, DeclarativeBase):
    """SQLAlchemy 2.0 native-dataclass declarative base."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)

    # Load server-generated values (ids, timestamps) via RETURNING on INSERT and
    # UPDATE: with AsyncSession an expired attribute can't be lazy-loaded.
    __mapper_args__ = {"eager_defaults": True}  # noqa: RUF012


class PrimaryKeyMixin(MappedAsDataclass):
    """Adds an autoincrement integer primary key ``id``."""

    id: Mapped[int] = mapped_column(
        primary_key=True,
        autoincrement=True,
        init=False,  # generated by the database, not a constructor argument
        sort_order=-9999,
    )


class TimestampMixin(MappedAsDataclass):
    """Adds created_at / updated_at audit timestamps."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
        init=False,  # set by the database, not a constructor argument
        sort_order=-9998,
    )

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
        init=False,
        sort_order=-9997,
    )


def enum_column(enum_cls: type[Enum], *, name: str, length: int = 32) -> sa.Enum:
    """Store a ``StrEnum`` as VARCHAR + CHECK (new values are a simple migration)."""
    return sa.Enum(
        enum_cls,
        name=name,
        native_enum=False,
        create_constraint=True,
        length=length,
        values_callable=lambda e: [member.value for member in e],
    )
